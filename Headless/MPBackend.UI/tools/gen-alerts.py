"""Generate Alerts/AlertTable.g.cs (CAS alert definitions) from the GCS design spec (ardupilot.alerts).

Usage: python gen-alerts.py <path-to-gcs-design-spec.json>
Entries without an id (relay box alerts) are skipped; they belong to the relay step.
"""
import json, sys, pathlib

spec = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
alerts = [a for a in spec["ardupilot"]["alerts"] if "id" in a]

def cs(s):
    return "null" if s is None else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = [
    f"// generated by tools/gen-alerts.py from {spec['meta']['name']} v{spec['meta']['version']} - do not edit",
    "namespace MPBackend.UI.Alerts;",
    "",
    "public static partial class AlertTable",
    "{",
    "    public static readonly IReadOnlyList<AlertDef> All = new AlertDef[]",
    "    {",
]
for a in alerts:
    level = "AlertLevel." + a["level"].capitalize()
    lines.append(f"        new({cs(a['id'])}, {level}, {cs(a['text'])}, {cs(a.get('trigger'))}, {cs(a.get('action'))}, {cs(a.get('avionicsAnalog'))}),")
lines += ["    };", "}", ""]
out = pathlib.Path(__file__).resolve().parent.parent / "Alerts" / "AlertTable.g.cs"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} ({len(alerts)} alerts)")
