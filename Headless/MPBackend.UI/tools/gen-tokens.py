"""Generate wwwroot/css/tokens.css from the GCS design spec (gcs-design-spec.json).

Usage: python gen-tokens.py <path-to-gcs-design-spec.json>
Palette entries become --p-<name>, semantic entries --c-<name> (dots replaced by dashes; gradient pairs
become --c-<name>-0/-1, bg/fg/border become --c-<name>-bg/-fg/-border). Typography sizes become --fs-<name>.
"""
import json, sys, pathlib

spec = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
pal = spec["tokens"]["color"]["palette"]
sem = spec["tokens"]["color"]["semantic"]
typo = spec["tokens"]["typography"]
motion = spec["tokens"]["motion"]
spacing = spec["tokens"]["spacing"]

def ref(v):
    return f"var(--p-{v})" if v in pal else v

lines = [f"/* generated by tools/gen-tokens.py from {spec['meta']['name']} v{spec['meta']['version']} - do not edit */", ":root {"]
for k, v in pal.items():
    lines.append(f"  --p-{k}: {v};")
for k, v in sem.items():
    name = k.replace(".", "-")
    val = v.get("value")
    if isinstance(val, list):
        for i, x in enumerate(val):
            lines.append(f"  --c-{name}-{i}: {ref(x)};")
    elif val is not None:
        lines.append(f"  --c-{name}: {ref(val)};")
    for extra in ("bg", "fg", "border", "outline"):
        if extra in v:
            lines.append(f"  --c-{name}-{extra}: {ref(v[extra])};")
for k, v in typo["sizes"].items():
    lines.append(f"  --fs-{k}: {v['size']}px;")
    lines.append(f"  --fw-{k}: {v['weight']};")
lines.append(f"  --font-inst: 'Roboto Condensed', 'Barlow Semi Condensed', {typo['family']['fallback']};")
for k, v in motion.items():
    if isinstance(v, (int, float)):
        lines.append(f"  --motion-{k}: {v}ms;" if k.endswith("_ms") else f"  --motion-{k}: {v};")
for k, v in spacing.items():
    if isinstance(v, (int, float)):
        lines.append(f"  --sp-{k}: {v}px;")
lines.append("}")
out = pathlib.Path(__file__).resolve().parent.parent / "wwwroot" / "css" / "tokens.css"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out} ({len(lines)} lines)")
