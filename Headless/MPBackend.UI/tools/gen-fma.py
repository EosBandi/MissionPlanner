"""Generate Pfd/FmaTable.g.cs (flight mode annunciator mapping) from the GCS design spec (ardupilot.fma).

Usage: python gen-fma.py <path-to-gcs-design-spec.json>
"""
import json, sys, pathlib

spec = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding="utf-8"))
fma = spec["ardupilot"]["fma"]

def cs(s):
    return "null" if s is None else '"' + s.replace('"', '\\"') + '"'

lines = [
    f"// generated by tools/gen-fma.py from {spec['meta']['name']} v{spec['meta']['version']} - do not edit",
    "namespace MPBackend.UI.Pfd;",
    "",
    "public static partial class FmaTable",
    "{",
    "    public static readonly IReadOnlyDictionary<string, IReadOnlyDictionary<string, FmaMode>> Modes =",
    "        new Dictionary<string, IReadOnlyDictionary<string, FmaMode>>(StringComparer.OrdinalIgnoreCase)",
    "        {",
]
for veh in ("plane", "copter"):
    lines.append(f"            [{cs(veh)}] = new Dictionary<string, FmaMode>(StringComparer.OrdinalIgnoreCase)")
    lines.append("            {")
    for mode, m in fma[veh].items():
        lines.append(f"                [{cs(mode)}] = new FmaMode({cs(m['lat'])}, {cs(m['vert'])}, {cs(m.get('armedLat'))}, {cs(m.get('armedVert'))}, {cs(m['authority'])}, {cs(m.get('statusColor'))}),")
    lines.append("            },")
lines += ["        };", "}", ""]
out = pathlib.Path(__file__).resolve().parent.parent / "Pfd" / "FmaTable.g.cs"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out}")
